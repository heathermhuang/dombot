import { build } from 'esbuild';
import { writeFile } from 'node:fs/promises';
const scripts = [];
for (const [name, entry] of [
  ['authScript', 'hosted/browser-auth.ts'],
  ['importStartScript', 'hosted/browser-import.ts'],
  ['parkioMobileScript', 'hosted/parkio-mobile.ts'],
  ['parkioNativeScript', 'hosted/parkio-native.ts'],
]) {
  const result = await build({
    entryPoints: [entry],
    bundle: true,
    minify: true,
    format: 'esm',
    platform: 'browser',
    write: false,
    target: ['es2022'],
  });
  scripts.push(
    `export const ${name}=${JSON.stringify(result.outputFiles[0].text)};`,
  );
}
await writeFile(
  'hosted/generated-auth.ts',
  `// Generated by node hosted/build-auth.mjs; do not edit.\n${scripts.join('\n')}\n`,
);
