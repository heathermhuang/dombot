import { build } from 'esbuild';
import { writeFile } from 'node:fs/promises';
const result = await build({
  entryPoints: ['hosted/browser-auth.ts'],
  bundle: true,
  minify: true,
  format: 'esm',
  platform: 'browser',
  write: false,
  target: ['es2022'],
});
await writeFile(
  'hosted/generated-auth.ts',
  `// Generated by node hosted/build-auth.mjs; do not edit.\nexport const authScript=${JSON.stringify(result.outputFiles[0].text)};\n`,
);
